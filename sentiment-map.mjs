// 恐慌评分映射：绝对严重度分 score → 0~100 **经验分位** sent，以及档位定义。
// 被 analyze-dt.mjs 与 sentiment-backtest.mjs 共用，确保两边算出来的 sent 逐位一致
// （此前两处各写一份公式，改动时极易漂移）。
//
//   score = max(跌停家数/60, 跌停市值占比%/1.0, 权重股跌停数/12)   —— 绝对强度，无上界
//   sent  = 把 score 在窗口内的名次换算成**经验分位**，直接 ×100，并列值按日期顺序展开
//
// ⚠️ 2026-10-13 改过一次，原因值得留档：
//   原来写的是 sent = 50 + 15·Φ⁻¹(p)。只要 p 是经验分位（近似均匀），
//   过一遍 Φ⁻¹ 出来**必然**是 N(50,15²) —— 所以「恐慌分位符合高斯分布」是构造出来的恒等式，
//   不是市场给的性质。实测验证：743 天里 sent 的 1%/5%/50%/95%/99% 分位是
//   15.2 / 25.4 / 50 / 74.4 / 84.1，与 N(50,15²) 的理论值 15.1 / 25.3 / 50 / 74.7 / 84.9 逐个吻合。
//   而那个「漂亮的正态分布图」会让人以为看出了什么规律。改成分位后：
//     · 数字的含义变成「今天在窗口里排第几」—— 可以直接核对，不再需要信一个变换；
//     · 分布会显示成**均匀**的，这才是真实情况（排名本来就是均匀的）；
//     · 档位门槛从 74.7/78.2/84.9 变成 95/97/99，可以直接读成「最严重的 5%/3%/1%」。
//   注意：**绝对分值没有意义**。score = max(跌停家数/60, 市值占比/1.0, 权重股/12)，
//   那三个分母（60 / 1.0 / 12）是约定，不是推导出来的。只有**排名**才是有依据的。
//
// 为什么档位挂在 sent 而不是 score：
//   score 无上界且重尾。实测三年窗口里最惨的一天（2025-04-07，2815 家跌停、市值占比 33.4%）
//   score = 46.92，而写死的橙档门槛是 3.0 —— 同一个橙色里塞进了相差 15.6 倍的事件。
//   sent 是排名映射，天然有界（0~100），且与面板上的刻度条是同一个量纲。
export const NORM = { dt: 60, cap: 1.0, mem: 12 };

export const scoreOf = (v) =>
  Math.max(v.dt / NORM.dt, (v.allCap ? (v.dtCap / v.allCap) * 100 : 0) / NORM.cap, v.mem / NORM.mem);

/**
 * Acklam 逆正态近似，相对误差 < 1.15e-9。
 * ⚠️ 2026-10-13 起**已不在情绪分的生产路径里**（sent 改为直接输出分位）。
 *    保留是因为 analyze-window-impact.mjs 还在用它复现「窗口长度对旧口径的影响」那段历史分析。
 *    新代码不要再用它算 sent。
 */
export function normInv(p) {
  const a = [-3.969683028665376e1, 2.209460984245205e2, -2.759285104469687e2, 1.38357751867269e2, -3.066479806614716e1, 2.506628277459239];
  const b = [-5.447609879822406e1, 1.615858368580409e2, -1.556989798598866e2, 6.680131188771972e1, -1.328068155288572e1];
  const c = [-7.784894002430293e-3, -3.223964580411365e-1, -2.400758277161838, -2.549732539343734, 4.374664141464968, 2.938163982698783];
  const d = [7.784695709041462e-3, 3.224671290700398e-1, 2.445134137142996, 3.754408661907416];
  const pl = 0.02425;
  if (p <= 0) return -38;
  if (p >= 1) return 38;
  let q, r;
  if (p < pl) { q = Math.sqrt(-2 * Math.log(p)); return (((((c[0] * q + c[1]) * q + c[2]) * q + c[3]) * q + c[4]) * q + c[5]) / ((((d[0] * q + d[1]) * q + d[2]) * q + d[3]) * q + 1); }
  if (p > 1 - pl) { q = Math.sqrt(-2 * Math.log(1 - p)); return -(((((c[0] * q + c[1]) * q + c[2]) * q + c[3]) * q + c[4]) * q + c[5]) / ((((d[0] * q + d[1]) * q + d[2]) * q + d[3]) * q + 1); }
  q = p - 0.5; r = q * q;
  return (((((a[0] * r + a[1]) * r + a[2]) * r + a[3]) * r + a[4]) * r + a[5]) * q / (((((b[0] * r + b[1]) * r + b[2]) * r + b[3]) * r + b[4]) * r + 1);
}

/**
 * 传入按日期升序的 score 数组，返回同顺序的 sent 数组。
 * sent = 经验分位 × 100（0~100），50 = 窗口中位数。
 * ⚠️ 不要再乘 15 过 Φ⁻¹ —— 那会让分布变成构造出来的正态（见文件头说明）。
 */
export function makeSentOf(scores) {
  const order = scores
    .map((v, i) => [v, i])
    .filter(([v]) => isFinite(v))
    .sort((x, y) => x[0] - y[0] || x[1] - y[1]); // 并列按日期顺序展开，否则同分日会挤成一个读数
  const N = order.length;
  const out = new Array(scores.length).fill(50); // 无效值的兜底 = 中位分位
  if (!N) return out;
  for (let k = 0; k < N; k++) {
    const p = Math.min(Math.max((k + 0.5) / N, 1e-4), 1 - 1e-4);
    out[order[k][1]] = +(p * 100).toFixed(1); // ← 分位本身就是 sent，不再做正态变换
  }
  return out;
}

/** 由「日期 → 原始计数」得到「日期 → {score, sent}」，窗口取最后 window 天（window<=0 表示全部） */
export function buildSeries(counts, window = 0) {
  let dates = Object.keys(counts).sort();
  if (window > 0 && dates.length > window) dates = dates.slice(-window);
  const sc = dates.map((d) => scoreOf(counts[d]));
  const sent = makeSentOf(sc);
  const map = new Map();
  dates.forEach((d, i) => map.set(d, { d, score: +sc[i].toFixed(2), sent: +sent[i].toFixed(1) }));
  return { dates, map };
}

// ---------------------------------------------------------------------------
// 档位：按恐慌分位切三档，就是窗口内最严重的 5% / 3% / 1% —— 阈值直接是分位数。
// 与窗口长度无关（分位天然归一），样本从 300 天拉到 3 年也不用重标。
//
// ⚠️ 标签改过一次：原来是「警觉 / 强恐慌 / 极端」。那是**给分位起的临床名字**，
//    会让 1/20 的普通日子听起来像市场状态诊断。现在直接写清楚它是什么：
//    「最严重的 5%」—— 一个纯统计陈述，不暗示任何后续走势。
// ---------------------------------------------------------------------------
export const TIER_PCT = [
  { name: '粉', label: '最严重的 5%', pct: 0.05, sentLo: 95, color: '#ec4899' },
  { name: '紫', label: '最严重的 3%', pct: 0.03, sentLo: 97, color: '#a855f7' },
  { name: '橙', label: '最严重的 1%', pct: 0.01, sentLo: 99, color: '#f59e0b' },
];

/** 生成带上下界的档位（与 TIER_PCT 同序：由宽到严） */
export function tiers() {
  return TIER_PCT.map((t, i) => ({
    ...t,
    sentHi: i + 1 < TIER_PCT.length ? TIER_PCT[i + 1].sentLo : Infinity,
  }));
}

// ---------------------------------------------------------------------------
// 乐观侧镜像档位：乐观指数 = 100 − 恐慌分位。
//   改成分位口径后这层镜像反而更清楚了：「乐观指数 ≥ 95」⟺「恐慌分位 ≤ 5」，
//   含义是「比今天更恐慌的日子不到 5%」，可以直接读、可以直接核对。
//   （旧的 50+15·Φ⁻¹ 口径下这里还绕过一次弯，见下面保留的教训。）
//   ⚠️ 门槛与恐慌侧是**同一组数字** 95 / 97 / 99 —— 因为两侧在同一个 0~100 刻度上。
//   教训留档：一开始写成「门槛 = 100 − sentLo = 25.3」，方向搞反了 ——
//     那样最宽的一档会把 95% 的点全吞进去，等于没分档。
//   配色用冷色系（青/碧/绿）与恐慌侧（粉/紫/橙）对称：同一分位、不同色相。
// ---------------------------------------------------------------------------
export const TIER_PCT_OPT = [
  { name: '青', label: '最乐观的 5%', color: '#22d3ee' },
  { name: '碧', label: '最乐观的 3%', color: '#2dd4bf' },
  { name: '绿', label: '最乐观的 1%', color: '#22c55e' },
];

/** 乐观侧档位（与 tiers() 同序：由宽到严），门槛与恐慌侧同值（同一刻度上的前 5%/3%/1%） */
export function tiersOpt() {
  return TIER_PCT.map((t, i) => ({
    name: TIER_PCT_OPT[i].name,
    label: TIER_PCT_OPT[i].label,
    color: TIER_PCT_OPT[i].color,
    pct: t.pct,
    minOptimism: t.sentLo,
    // 等价写法（情绪分侧），便于核对与展示
    maxSent: +(100 - t.sentLo).toFixed(1),
  }));
}
